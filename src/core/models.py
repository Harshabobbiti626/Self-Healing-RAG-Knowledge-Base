from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, List, Literal, Optional
from pydantic import BaseModel, Field


class ContentType(str, Enum):
    MARKDOWN = "markdown"
    TEXT = "text"
    PDF = "pdf"
    DOCX = "docx"
    JSON = "json"


class Document(BaseModel):
    """Represents an ingested source document with enterprise metadata."""
    doc_id: str
    title: str
    content: str
    content_type: ContentType = ContentType.TEXT
    version: str = "1.0"
    author: Optional[str] = None
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    valid_from: Optional[datetime] = None
    valid_until: Optional[datetime] = None
    metadata: Dict[str, Any] = Field(default_factory=dict)
    is_deprecated: bool = False


class Chunk(BaseModel):
    """Represents a discrete semantic chunk enriched with contextual headers."""
    chunk_id: str
    doc_id: str
    content: str
    contextual_prefix: str = ""  # Anthropic contextual retrieval header
    chunk_index: int = 0
    metadata: Dict[str, Any] = Field(default_factory=dict)
    is_active: bool = True
    is_golden: bool = False  # Flag for curated or self-healed golden chunks
    superseded_by: Optional[str] = None
    embedding: Optional[List[float]] = None

    @property
    def full_contextual_text(self) -> str:
        """Text used for embedding and retrieval."""
        if self.contextual_prefix:
            return f"[Context: {self.contextual_prefix}]\n{self.content}"
        return self.content


class RelevanceStatus(str, Enum):
    RELEVANT = "relevant"
    AMBIGUOUS = "ambiguous"
    IRRELEVANT = "irrelevant"


class DocumentRelevance(BaseModel):
    """Grading result for a retrieved chunk evaluated against the user query."""
    chunk_id: str
    score: float = Field(ge=0.0, le=1.0)
    status: RelevanceStatus
    reasoning: str = ""


class ClaimVerification(BaseModel):
    """Claim-level grounding and faithfulness verification."""
    claim: str
    is_grounded: bool
    status: Literal["grounded", "contradicted", "unsupported"]
    supporting_chunk_ids: List[str] = Field(default_factory=list)
    critique: Optional[str] = None


class GroundingVerdict(BaseModel):
    """Aggregate hallucination & faithfulness evaluation of generated answer."""
    is_faithful: bool
    hallucination_score: float = Field(default=0.0, ge=0.0, le=1.0)
    claims: List[ClaimVerification] = Field(default_factory=list)
    citations: List[str] = Field(default_factory=list)
    critique_feedback: Optional[str] = None


class FailureType(str, Enum):
    KNOWLEDGE_GAP = "knowledge_gap"  # Query topic completely absent from KB
    SEMANTIC_BLEED = "semantic_bleed"  # Chunk split midway through key facts
    TEMPORAL_CONTRADICTION = "temporal_contradiction"  # Newer doc conflicts with older doc
    VOCABULARY_BLINDSPOT = "vocabulary_blindspot"  # Missing synonyms / acronyms
    LOW_CONFIDENCE = "low_confidence"  # Ambiguous retrieval scores


class TelemetrySignal(BaseModel):
    """Runtime trace capturing query lifecycle for Slow-Loop analysis."""
    signal_id: str
    query: str
    rewritten_query: Optional[str] = None
    retrieved_chunk_ids: List[str] = Field(default_factory=list)
    grader_scores: List[float] = Field(default_factory=list)
    avg_relevance: float = 0.0
    grounding_passed: bool = True
    hallucination_detected: bool = False
    retry_count: int = 0
    fallback_used: bool = False
    user_feedback: Optional[float] = None  # -1.0 (thumbs down), 1.0 (thumbs up)
    latency_ms: float = 0.0
    timestamp: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))


class HealingAction(BaseModel):
    """Autonomous repair action generated by the Slow Loop."""
    patch_id: str
    failure_type: FailureType
    target_doc_id: Optional[str] = None
    target_chunk_id: Optional[str] = None
    action_type: Literal[
        "re_chunk",
        "deprecate_chunk",
        "inject_reflection_qa",
        "alert_knowledge_gap",
        "resolve_conflict",
    ]
    details: Dict[str, Any] = Field(default_factory=dict)
    applied: bool = False
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
